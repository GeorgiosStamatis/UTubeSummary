@Serializable
data class YouTubeTranscript(
    @property:LLMDescription("The full URL of the YouTube video.") val url: String,
    @property:LLMDescription("Language code of the subtitles to prefer when the video has several, or null.")
    val preferredLanguage: String? = null,
)

class YouTubeTranscriptTool(client: HttpClient) : Tool<YouTubeTranscript, ExtractedContent>(
    argsType = typeToken<YouTubeTranscript>(),
    resultType = typeToken<ExtractedContent>(),
    name = "extract_transcript_from_youtube_url",
    description = "Fetches the transcript for a given YouTube video URL."
) {
    private val youtubeExtractor = YouTubeExtractor(client)


    override suspend fun execute(args: YouTubeTranscript): ExtractedContent {
        val videoId = YouTubeExtractor.extractVideoId(args.url)
            ?: throw Exception("Could not extract video ID from URL: ${args.url}")
        val (details, playerResponse) = youtubeExtractor.getVideoDetails(videoId)
        val transcript = youtubeExtractor.getTranscript(
            videoId,
            playerResponse,
            preferredLanguages = listOfNotNull(args.preferredLanguage, "en").distinct(),
        )
        return ExtractedContent(
            title = details.title,
            author = details.author,
            content = transcript.text,
            languageCode = transcript.languageCode,
            isAutoGenerated = transcript.isAutoGenerated,
        )
    }

    companion object {
        fun isYouTubeLink(input: String): Boolean = VideoSubtype.isYouTube(input)

        /** The video id of any YouTube link form (watch, youtu.be, shorts, embed, live), or null. */
        fun extractVideoId(url: String): String? = YouTubeExtractor.extractVideoId(url)
    }
}

private data class VideoDetails(val title: String, val author: String)

@Serializable
internal data class CaptionTrack(
    val baseUrl: String,
    val name: Name,
    val languageCode: String,
    val kind: String? = null, // "asr" for auto-generated
) {
    @Serializable
    data class Name(val simpleText: String = "")
}

/** The language without region or script: `en-US` and `en` are both `en`. */
private fun baseLanguage(code: String): String = code.substringBefore('-').lowercase()

/**
 * Picks the caption track to read.
 *
 * Videos with automatic dubbing or translation list auto-generated ("asr") tracks in many languages, so
 * the first auto track is **not** the spoken language. The spoken language is taken from, in order:
 * [originalAudioLanguage], the track YouTube marks as default ([defaultTrackIndex]), the only auto
 * track, or the language that has both a manual and an auto track. Then the order is: a manual track in
 * the spoken language, a manual track in a wanted language ([preferredLanguages], in that order), the
 * auto track of the spoken language, YouTube's default track, an auto track in a wanted language, any
 * track in a wanted language, the first track. Languages match by their base (`en-US` is `en`).
 */
internal fun selectCaptionTrack(
    tracks: List<CaptionTrack>,
    preferredLanguages: List<String> = listOf("en"),
    defaultTrackIndex: Int? = null,
    originalAudioLanguage: String? = null,
): CaptionTrack? {
    val manual = tracks.filter { it.kind != "asr" }
    val auto = tracks.filter { it.kind == "asr" }
    val wanted = preferredLanguages.map(::baseLanguage)

    val spoken: String? = originalAudioLanguage?.takeIf { it.isNotBlank() }?.let(::baseLanguage)
        ?: defaultTrackIndex?.let { tracks.getOrNull(it) }?.let { baseLanguage(it.languageCode) }
        ?: auto.singleOrNull()?.let { baseLanguage(it.languageCode) }
        ?: auto.map { baseLanguage(it.languageCode) }.firstOrNull { language ->
            manual.any { baseLanguage(it.languageCode) == language }
        }

    fun manualIn(language: String): CaptionTrack? =
        manual.firstOrNull { it.languageCode.equals(language, ignoreCase = true) }
            ?: manual.firstOrNull { baseLanguage(it.languageCode) == language }

    return spoken?.let { manualIn(it) }
        ?: wanted.firstNotNullOfOrNull { manualIn(it) }
        ?: spoken?.let { language -> auto.firstOrNull { baseLanguage(it.languageCode) == language } }
        ?: defaultTrackIndex?.let { tracks.getOrNull(it) }
        ?: wanted.firstNotNullOfOrNull { language -> auto.firstOrNull { baseLanguage(it.languageCode) == language } }
        ?: wanted.firstNotNullOfOrNull { language -> tracks.firstOrNull { baseLanguage(it.languageCode) == language } }
        ?: tracks.firstOrNull()
}

/**
 * The index of the caption track YouTube itself shows by default (`audioTracks[].defaultCaptionTrackIndex`
 * of the player data), or null when the answer has none.
 */
internal fun defaultCaptionTrackIndex(playerResponse: JsonObject): Int? {
    val renderer = playerResponse["captions"]?.jsonObject?.get("playerCaptionsTracklistRenderer")?.jsonObject
        ?: return null
    val audioTracks = renderer["audioTracks"] as? JsonArray ?: return null
    val audioIndex = renderer["defaultAudioTrackIndex"]?.jsonPrimitive?.intOrNull ?: 0
    val audioTrack = (audioTracks.getOrNull(audioIndex) ?: audioTracks.firstOrNull()) as? JsonObject
    return audioTrack?.get("defaultCaptionTrackIndex")?.jsonPrimitive?.intOrNull?.takeIf { it >= 0 }
}

/**
 * The subtitle language to prefer for a summary: none when the summary follows the video's own
 * language, otherwise the language the summary is written in. The agent that carries this value is
 * cached by its system prompt, which names that same language, so a cached agent cannot hold a
 * different one.
 */
internal fun preferredTranscriptLanguage(
    useContentLanguage: Boolean,
    summaryLanguage: Locale?,
    appLanguage: Locale,
): String? =
    if (useContentLanguage) null else (summaryLanguage ?: appLanguage).language.takeIf { it.isNotBlank() }

/** The text of a transcript with its language; [isAutoGenerated] for speech recognition output. */
internal data class TranscriptResult(val text: String, val languageCode: String, val isAutoGenerated: Boolean)

/** Why YouTube will not give out this video (private, age or login restricted, removed), or null. */
internal fun playabilityProblem(playerResponse: JsonObject): String? {
    val playability = playerResponse["playabilityStatus"] as? JsonObject ?: return null
    val status = playability["status"]?.jsonPrimitive?.contentOrNull
    if (status != "LOGIN_REQUIRED" && status != "UNPLAYABLE" && status != "ERROR") return null
    return playability["reason"]?.jsonPrimitive?.contentOrNull ?: status
}


/**
 * ref: https://github.com/jdepoix/youtube-transcript-api/blob/d2a409d0ce7a7bd35fe6b911ac698038ebf599cc/youtube_transcript_api/_transcripts.py#L359
 */
private class YouTubeExtractor(private val client: HttpClient) {
    private val json = Json { ignoreUnknownKeys = true }

    companion object {
        private const val TAG = "YouTubeExtractor"

        private fun ensureScheme(url: String): String {
            return if (!url.matches(Regex("^https?://.*"))) {
                "https://$url"
            } else {
                url
            }
        }

        fun extractVideoId(urlInput: String): String? {
            try {
                val urlString = ensureScheme(urlInput)
                val url = Url(urlString)
                val host = url.host.lowercase()
                val pathSegments = url.segments

                val vid = when {
                    host == "youtu.be" -> pathSegments.firstOrNull()

                    host.endsWith("youtube.com") -> {
                        when (pathSegments.firstOrNull()) {
                            "watch" -> url.parameters["v"]
                            "live", "embed", "v", "shorts" -> pathSegments.getOrNull(1)
                            else -> {
                                // Fallback for URLs like youtube.com/VIDEO_ID or youtube.com/VIDEO_ID?foo=bar
                                if (pathSegments.isNotEmpty()
                                    && pathSegments.first().matches(Regex("[a-zA-Z0-9_-]{11}"))
                                ) {
                                    pathSegments.first()
                                } else {
                                    null
                                }
                            }
                        }
                    }

                    else -> null
                }

                // Standard YouTube video IDs are 11 characters long and use alphanumeric characters, underscores, and hyphens.
                return vid?.takeIf { it.matches(Regex("[a-zA-Z0-9_-]{11}")) }
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "Error parsing URL to extract video ID: $urlInput", e)
                return null
            }
        }
    }

    /**
     * Asks YouTube for the player data of [videoId] as [profile]: the watch page (for the public API
     * key), then the player API. Network exceptions are not caught: they say "no internet" later.
     */
    private suspend fun getPlayerOutcome(videoId: String, profile: InnertubeClient): PlayerOutcome =
        withContext(Dispatchers.IO) {
            val pageResponse = client.get("https://www.youtube.com/watch?v=$videoId") {
                headers {
                    append("Accept-Language", "en-US,en;q=0.9")
                }
            }
            if (!pageResponse.status.isSuccess()) {
                Log.e(TAG, "Failed to fetch watch page: ${pageResponse.status}")
                return@withContext PlayerOutcome.HttpError("watch page", pageResponse.status.value)
            }
            val html = pageResponse.bodyAsText()
            val apiKey = Regex("\"INNERTUBE_API_KEY\"\\s*:\\s*\"([^\"]+)\"").find(html)?.groupValues?.get(1)
            if (apiKey == null) {
                Log.e(TAG, "Could not find INNERTUBE_API_KEY in watch page HTML.")
                return@withContext PlayerOutcome.NoApiKey("watch page")
            }

            // Always use the /player API to fetch the player response, as it's more reliable
            // than parsing the inline JSON from the watch page, which might be incomplete.
            val response = client.post("https://www.youtube.com/youtubei/v1/player?key=$apiKey") {
                contentType(ContentType.Application.Json)
                requestHeaders(profile).forEach { (name, value) -> header(name, value) }
                setBody(playerRequestBody(profile, videoId).toString())
            }
            if (!response.status.isSuccess()) {
                Log.e(TAG, "Failed to fetch from /player API: ${response.status}. Body: ${response.bodyAsText()}")
                return@withContext PlayerOutcome.HttpError("player API", response.status.value)
            }
            val playerResponse = try {
                json.parseToJsonElement(response.bodyAsText()).jsonObject
            } catch (e: SerializationException) {
                Log.e(TAG, "The player API answer is not JSON", e)
                return@withContext PlayerOutcome.BadBody("player API")
            } catch (e: IllegalArgumentException) {
                Log.e(TAG, "The player API answer is not a JSON object", e)
                return@withContext PlayerOutcome.BadBody("player API")
            }
            classifyPlayerResponse(playerResponse)
        }

    /**
     * The title, author and player data of [videoId].
     * @throws SummaryException a restricted video is "unavailable"; any other failure is an
     * extraction failure with the client and step in its details.
     */
    suspend fun getVideoDetails(videoId: String): Pair<VideoDetails, JsonObject> {
        val profile = ANDROID_LEGACY
        val outcome = getPlayerOutcome(videoId, profile)
        Log.i(TAG, "Player data for $videoId as ${profile.label}: ${outcome::class.simpleName}")
        val playerResponse = (outcome as? PlayerOutcome.Playable)?.response ?: throw outcome.toFailure(profile)
        val details = playerResponse["videoDetails"]?.jsonObject
        val title = details?.get("title")?.jsonPrimitive?.contentOrNull
            ?: throw extractionFailed(profile, "no video title in the player data")
        // A missing author must not make an otherwise usable transcript fail.
        val author = details?.get("author")?.jsonPrimitive?.contentOrNull.orEmpty()
        return Pair(VideoDetails(title, author), playerResponse)
    }

    /**
     * The transcript text of the best caption track and its language code.
     * @throws SummaryException no captions at all is "no transcript"; a download that fails or an
     * empty or unreadable transcript is an extraction failure.
     */
    suspend fun getTranscript(
        videoId: String,
        playerResponse: JsonObject,
        preferredLanguages: List<String> = listOf("en"),
    ): TranscriptResult = withContext(Dispatchers.IO) {
        val profile = ANDROID_LEGACY
        val captionTracksJson = playerResponse["captions"]?.jsonObject
            ?.get("playerCaptionsTracklistRenderer")?.jsonObject
            ?.get("captionTracks")?.jsonArray
        if (captionTracksJson == null) {
            Log.w(TAG, "No caption tracks found for video $videoId.")
            throw SummaryException.NoTranscriptException()
        }

        val tracks = try {
            json.decodeFromJsonElement<List<CaptionTrack>>(captionTracksJson)
        } catch (e: SerializationException) {
            Log.e(TAG, "The caption track list is not readable", e)
            throw extractionFailed(profile, "caption track list unreadable")
        }
        if (tracks.isEmpty()) {
            Log.w(TAG, "No caption tracks found for video $videoId.")
            throw SummaryException.NoTranscriptException()
        }

        // Select the best track (prefer manual to auto, prefer the wanted languages over English)
        val track = selectCaptionTrack(tracks, preferredLanguages, defaultCaptionTrackIndex(playerResponse))
            ?: throw SummaryException.NoTranscriptException()
        Log.i(
            TAG,
            "Caption tracks for $videoId: ${tracks.joinToString { "${it.languageCode}${if (it.kind == "asr") "(auto)" else ""}" }}; " +
                    "chosen ${track.languageCode}${if (track.kind == "asr") "(auto)" else ""}"
        )

        val transcriptUrl = if (track.baseUrl.contains("fmt=srv3")) {
            track.baseUrl.replace("fmt=srv3", "fmt=json3")
        } else if (track.baseUrl.contains("?")) {
            "${track.baseUrl}&fmt=json3"
        } else {
            "${track.baseUrl}?fmt=json3"
        }
        val transcriptResponse = client.get(transcriptUrl) {
            // Mimic browser behavior; this is required for the request to succeed
            headers { append("Accept-Language", "${preferredLanguages.first()},en;q=0.9") }
            // The subtitle address belongs to the client that asked for it: same identity again.
            requestHeaders(profile).forEach { (name, value) -> header(name, value) }
        }
        if (!transcriptResponse.status.isSuccess()) {
            Log.e(TAG, "Failed to download transcript from $transcriptUrl: ${transcriptResponse.status}")
            throw extractionFailed(profile, "subtitle download: HTTP ${transcriptResponse.status.value}")
        }
        val transcriptJson = transcriptResponse.bodyAsText()
        if (transcriptJson.isEmpty()) {
            Log.e(TAG, "Transcript response body is empty for $transcriptUrl")
            throw extractionFailed(profile, "subtitle download: empty answer")
        }

        val transcriptText = parseJsonTranscript(transcriptJson)
        if (transcriptText.isBlank()) {
            throw extractionFailed(profile, "subtitle format not understood or empty")
        }
        TranscriptResult(transcriptText, track.languageCode, isAutoGenerated = track.kind == "asr")
    }

    private fun parseJsonTranscript(jsonString: String): String {
        return try {
            val jsonObject = json.parseToJsonElement(jsonString).jsonObject
            val events = jsonObject["events"]?.jsonArray ?: return ""
            val texts = mutableListOf<String>()

            for (event in events) {
                val eventObj = event.jsonObject
                if ("segs" in eventObj) {
                    val segs = eventObj["segs"]!!.jsonArray
                    for (seg in segs) {
                        val segObj = seg.jsonObject
                        if ("utf8" in segObj) {
                            texts.add(segObj["utf8"]!!.jsonPrimitive.content)
                        }
                    }
                }
            }
            // The JSON can contain newlines which should be spaces, and segments may or may not have spaces.
            // Joining with empty string and then replacing newline with space is the safest bet.
            texts.joinToString("").replace('\n', ' ').trim()
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Failed to parse JSON transcript", e)
            ""
        }
    }
}
